/* ZYRA Shop Assistant Widget (rule-based, no AI) */
(function () {
    const toggleBtn = document.getElementById('zyraAiChatToggle');
    const closeBtn = document.getElementById('zyraAiChatClose');
    const panel = document.getElementById('zyraAiChatPanel');
    const messagesEl = document.getElementById('zyraAiChatMessages');
    const suggestionsEl = document.getElementById('zyraAiChatSuggestions');
    const form = document.getElementById('zyraAiChatForm');
    const input = document.getElementById('zyraAiChatInput');
    const sendBtn = document.getElementById('zyraAiChatSend');

    if (!toggleBtn || !panel || !messagesEl || !form || !input) return;

    let busy = false;
    let greeted = false;

    function csrfToken() {
        return document.querySelector('meta[name="csrf-token"]')?.getAttribute('content') || '';
    }

    function addUserMessage(text) {
        const el = document.createElement('div');
        el.className = 'zyra-ai-msg user';
        el.textContent = text;
        messagesEl.appendChild(el);
        messagesEl.scrollTop = messagesEl.scrollHeight;
    }

    function addBotMessage(html) {
        const el = document.createElement('div');
        el.className = 'zyra-ai-msg bot';
        // Bot content is generated by our own server (links + formatting) — safe to render as HTML.
        el.innerHTML = html;
        messagesEl.appendChild(el);
        messagesEl.scrollTop = messagesEl.scrollHeight;
        return el;
    }

    function sendMessage(text) {
        const content = (text || '').trim();
        if (!content || busy) return;

        addUserMessage(content);

        const typingEl = addBotMessage('<i>Typing…</i>');
        busy = true;
        input.disabled = true;
        sendBtn.disabled = true;

        fetch('/chatbot/reply', {
            method: 'POST',
            headers: {
                'Content-Type': 'application/json',
                'Accept': 'application/json',
                'X-CSRF-TOKEN': csrfToken()
            },
            body: JSON.stringify({ message: content })
        })
            .then((res) => res.json())
            .then((data) => {
                typingEl.remove();
                addBotMessage((data && data.reply) ? data.reply : 'Sorry, something went wrong. Please try again.');
            })
            .catch(() => {
                typingEl.remove();
                addBotMessage('Sorry, there was a connection problem. Please try again.');
            })
            .finally(() => {
                busy = false;
                input.disabled = false;
                sendBtn.disabled = false;
                input.value = '';
                input.focus();
            });
    }

    form.addEventListener('submit', (e) => {
        e.preventDefault();
        sendMessage(input.value);
    });

    if (suggestionsEl) {
        suggestionsEl.addEventListener('click', (e) => {
            const btn = e.target.closest('button[data-q]');
            if (btn) sendMessage(btn.getAttribute('data-q'));
        });
    }

    toggleBtn.addEventListener('click', () => {
        const open = panel.hidden;
        panel.hidden = !open;
        toggleBtn.setAttribute('aria-expanded', open ? 'true' : 'false');
        if (open && !greeted) {
            greeted = true;
            addBotMessage('Hello, and welcome to ZYRA! Ask me things like <i>“Where is my order?”</i>, <i>“Return policy?”</i> or <i>“Any offers?”</i> — or tap a suggestion below.');
            input.focus();
        } else if (open) {
            input.focus();
        }
    });

    closeBtn.addEventListener('click', () => {
        panel.hidden = true;
        toggleBtn.setAttribute('aria-expanded', 'false');
    });
})();